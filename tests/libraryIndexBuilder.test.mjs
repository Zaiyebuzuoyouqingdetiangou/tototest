test('the verified packager rebuilds and checks indexes before creating the ZIP', () => {
    const source = readFileSync(join(ROOT, 'scripts/package-candidate.mjs'), 'utf8');
    const writeAt = source.indexOf('writeLibraryIndexes(root)');
    const checkAt = source.indexOf('checkLibraryIndexes(root)', writeAt);
    const testsAt = source.indexOf('runTests(root)', checkAt);
    const zipAt = source.indexOf("'create'", testsAt);
    const extractedCheckAt = source.indexOf('checkLibraryIndexes(extractedRoot)', zipAt);
    assert.ok(writeAt >= 0 && writeAt < checkAt, 'packaging must rebuild before checking');
    assert.ok(checkAt < testsAt, 'index check must precede source tests');
    assert.ok(testsAt < zipAt, 'tests must pass before ZIP creation');
    assert.ok(zipAt < extractedCheckAt, 'the exact extracted ZIP must be checked again');
});

