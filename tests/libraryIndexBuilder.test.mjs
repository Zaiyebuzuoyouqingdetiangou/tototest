const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURE_FILES = [
    'data/raw/rawPresentationFormats.js',
    'data/raw/rawThematicCategories.js',
    'data/metadata/presentationIndexMetadata.json',
    'data/metadata/thematicIndexMetadata.json',
    'data/structured/presentationIndex.js',
    'data/structured/thematicIndex.js',
];

function createFixture() {
    const fixture = mkdtempSync(join(tmpdir(), 'rabbitmirror-library-builder-'));
    for (const relative of FIXTURE_FILES) {
        const target = join(fixture, relative);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, readFileSync(join(ROOT, relative)));
    }
    return fixture;
}

function withFixture(run) {
    const fixture = createFixture();
    try {
        return run(fixture);
    } finally {
        rmSync(fixture, { recursive: true, force: true });
    }
}

function mutateText(root, relative, transform) {
    const file = join(root, relative);
    const before = readFileSync(file, 'utf8');
    const after = transform(before);
    assert.notEqual(after, before, `${relative} mutation must change the fixture`);
    writeFileSync(file, after, 'utf8');
}

function mutateJson(root, relative, transform) {
    const file = join(root, relative);
    const value = JSON.parse(readFileSync(file, 'utf8'));
    transform(value);
    writeFileSync(file, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function generatedByKind(results, kind) {
    return results.find(result => result.config.kind === kind);
}

test('current checked-in indexes are exactly the deterministic build output', () => {
    const first = checkLibraryIndexes(ROOT, { quiet: true });
    const second = buildAllLibraryIndexes(ROOT);
    assert.deepEqual(first.map(result => [result.config.kind, result.items.length]), [
        ['presentation', 208],
        ['theme', 165],
    ]);
    for (const result of first) {
        const repeated = generatedByKind(second, result.config.kind);
        assert.equal(result.changed, false, `${result.config.kind} index must be current`);
        assert.equal(result.generatedSource, result.currentSource, `${result.config.kind} generated bytes must equal checked-in bytes`);
        assert.equal(repeated.generatedSource, result.generatedSource, `${result.config.kind} builds must be byte-deterministic`);
    }
});

test('write mode updates only the selected mother entry and check mode then passes', () => withFixture(root => {
    mutateText(root, 'data/raw/rawPresentationFormats.js', source => source.replace(
        '角色自制榜等，题材与风格不限。',
        '角色自制榜等，题材、风格与媒介不限。',
    ));
    assert.throws(() => checkLibraryIndexes(root, { quiet: true }), /generated indexes are stale/);
    const written = writeLibraryIndexes(root, { quiet: true });
    assert.deepEqual(written.changed.map(result => result.config.kind), ['presentation']);
    checkLibraryIndexes(root, { quiet: true });
    const presentation = generatedByKind(buildAllLibraryIndexes(root), 'presentation');
    const ranking = presentation.items.find(item => item.id === '1.3.4');
    assert.match(ranking.summary, /题材、风格与媒介不限/);
    assert.match(ranking.raw, /题材、风格与媒介不限/);
}));

