test('candidate packaging stops before ZIP creation when a mother entry gains a plain continuation', () => {
    const sandbox = mkdtempSync(join(tmpdir(), 'rabbitmirror-library-package-guard-'));
    const root = join(sandbox, 'tototest-main');
    const output = join(sandbox, 'should-not-exist.zip');
    try {
        cpSync(ROOT, root, { recursive: true });
        mutateText(root, 'data/raw/rawPresentationFormats.js', source => source.replace(
            '* **6.2.5 修仙养成**：高自由度修仙养成游戏，可自由探索、修炼、结缘、攻略不同人物并触发大量随机事件与关系变化；允许「海王」式多线发展。',
            '* **6.2.5 修仙养成**：高自由度修仙养成游戏，可自由探索、修炼、结缘、攻略不同人物并触发大量随机事件与关系变化；允许「海王」式多线发展。\n    第二行继续说明，绝不能被静默丢弃。',
        ));
        const result = spawnSync(process.execPath, [
            'scripts/package-candidate.mjs',
            '--root', root,
            '--output', output,
        ], {
            cwd: root,
            encoding: 'utf8',
            maxBuffer: 16 * 1024 * 1024,
        });
        assert.notEqual(result.status, 0, 'packaging must fail closed');
        assert.match(`${result.stdout || ''}${result.stderr || ''}`, /must remain on one line/);
        assert.equal(existsSync(output), false, 'invalid mother library must not produce a ZIP');
    } finally {
        rmSync(sandbox, { recursive: true, force: true });
    }
});

test('build tooling is not imported by the browser runtime graph', () => {
    const runtimeFiles = [join(ROOT, 'index.js')];
    const visit = current => {
        for (const entry of readdirSync(current, { withFileTypes: true })) {
            const full = join(current, entry.name);
            if (entry.isDirectory()) visit(full);
            else if (/\.m?js$/.test(entry.name)) runtimeFiles.push(full);
        }
    };
    visit(join(ROOT, 'src'));
    visit(join(ROOT, 'data'));

    for (const file of runtimeFiles) {
        const source = readFileSync(file, 'utf8');
        assert.doesNotMatch(source, /build-library-indexes|package-candidate|create-extension-zip/, `${file} must not load build-only tooling at runtime`);
    }
});
